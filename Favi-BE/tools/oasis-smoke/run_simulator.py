"""Run the upstream OASIS engine with ManualAction, then export its actual database.

No SQL inserts/schema fabrication and no LLM inference. This tests simulator integration,
not autonomous agent behavior. StubModel only satisfies the SocialAgent constructor.
"""
import asyncio
import hashlib
import importlib.util
import importlib.metadata
import json
import os
import sqlite3
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from source_provenance import verify_runtime_source, verify_dependency_lock

PINNED_OASIS_COMMIT = "ba892e0667eb84b312e4c0e5630f275154bbb98f"


async def simulate(root, upstream):
    spec = importlib.util.find_spec("oasis")
    if spec is None or spec.origin is None:
        raise RuntimeError("OASIS package not installed")
    source_identity = verify_runtime_source(upstream, Path(spec.origin).parent, PINNED_OASIS_COMMIT)
    if importlib.metadata.version("camel-oasis") != "0.2.5":
        raise RuntimeError("Unexpected camel-oasis distribution version")
    locked_versions = verify_dependency_lock(Path(__file__).with_name("requirements-oasis.lock.txt"))
    # Upstream creates ./log at import; keep its runtime artifacts outside source.
    os.chdir(root)
    (root / "log").mkdir(exist_ok=True)
    from camel.models import StubModel
    from camel.types import ModelType
    import oasis
    if Path(oasis.__file__).resolve().parent != Path(spec.origin).resolve().parent:
        raise RuntimeError("OASIS module resolution changed during import")
    from oasis import ActionType, AgentGraph, ManualAction, SocialAgent, UserInfo
    from oasis.clock.clock import Clock
    from oasis.social_platform.platform import Platform

    commit = subprocess.check_output(["git", "-C", str(upstream), "rev-parse", "HEAD"], text=True).strip()
    if commit != PINNED_OASIS_COMMIT:
        raise RuntimeError("Unexpected upstream commit; review before updating the pinned integration")
    graph = AgentGraph()
    model = StubModel(model_type=ModelType.STUB)
    actions = [ActionType.CREATE_POST, ActionType.LIKE_POST, ActionType.FOLLOW, ActionType.CREATE_COMMENT]
    agents = []
    for index in range(3):
        agent = SocialAgent(agent_id=index, user_info=UserInfo(user_name=f"favi_agent_{index}",
            name=f"Tác giả {index}", description="Du lịch và ẩm thực", profile=None, recsys_type="reddit"),
            agent_graph=graph, model=model, available_actions=actions)
        graph.add_agent(agent)
        agents.append(agent)
    database = root / "oasis.db"
    os.environ["OASIS_DB_PATH"] = str(database)
    # OASIS Reddit expects naive timestamps. Explicit UTC-naive simulation origin
    # keeps them compatible with the adapter's UTC contract on a Windows UTC+7 host.
    platform = Platform(db_path=str(database), recsys_type="reddit", sandbox_clock=Clock(k=1),
        start_time=datetime.now(timezone.utc).replace(tzinfo=None))
    env = oasis.make(agent_graph=graph, platform=platform, database_path=str(database))
    await env.reset()
    async def step(agent, kind, arguments):
        await env.step({agent: ManualAction(action_type=kind, action_args=arguments)})
    try:
        captions = ["Ảnh 'đẹp'; \\ du lịch", "Restricted metadata test", "Ẩm thực Việt Nam"]
        for agent, caption in zip(agents, captions):
            await step(agent, ActionType.CREATE_POST, {"content": caption})
        # Read IDs generated by OASIS; never assume autoincrement values.
        with sqlite3.connect(f"file:{database.as_posix()}?mode=ro", uri=True) as db:
            posts = [row[0] for row in db.execute("SELECT post_id FROM post ORDER BY post_id")]
        await step(agents[1], ActionType.LIKE_POST, {"post_id": posts[0]})
        await step(agents[0], ActionType.LIKE_POST, {"post_id": posts[1]})
        await step(agents[0], ActionType.LIKE_POST, {"post_id": posts[2]})
        await step(agents[1], ActionType.FOLLOW, {"followee_id": 0})
        await step(agents[1], ActionType.CREATE_COMMENT, {"post_id": posts[0], "content": "Nice'); DROP TABLE Posts; --"})
    finally:
        await env.close()
    with sqlite3.connect(f"file:{database.as_posix()}?mode=ro", uri=True) as db:
        if db.execute("PRAGMA integrity_check").fetchall() != [("ok",)]:
            raise ValueError("SQLite integrity check failed")
        supported_fk_checks = {table: db.execute(f'PRAGMA foreign_key_check("{table}")').fetchall()
                               for table in ("user", "post", "like", "follow", "comment")}
        # Pinned upstream incorrectly declares like.post_id -> tweet(post_id),
        # while its own create_post/like actions operate on post. Do not rewrite
        # source schema: validate every logical reference below and report DDL bugs.
        for table, failures in supported_fk_checks.items():
            if failures and not (table == "like" and all(row[2] == "tweet" for row in failures)):
                raise ValueError(f"Unexpected physical FK failures: {supported_fk_checks}")
        semantic_queries = {
            "post.user": 'SELECT p.post_id FROM post p LEFT JOIN user u ON u.user_id=p.user_id WHERE u.user_id IS NULL',
            "like.user/post": 'SELECT l.like_id FROM "like" l LEFT JOIN user u ON u.user_id=l.user_id LEFT JOIN post p ON p.post_id=l.post_id WHERE u.user_id IS NULL OR p.post_id IS NULL',
            "follow.users": 'SELECT f.follow_id FROM follow f LEFT JOIN user a ON a.user_id=f.follower_id LEFT JOIN user b ON b.user_id=f.followee_id WHERE a.user_id IS NULL OR b.user_id IS NULL',
            "comment.user/post": 'SELECT c.comment_id FROM comment c LEFT JOIN user u ON u.user_id=c.user_id LEFT JOIN post p ON p.post_id=c.post_id WHERE u.user_id IS NULL OR p.post_id IS NULL',
        }
        semantic_fk_checks = {name: db.execute(query).fetchall() for name, query in semantic_queries.items()}
        if any(semantic_fk_checks.values()):
            raise ValueError(f"Semantic FK failures: {semantic_fk_checks}")
        ignored_schema_issue = None
        try:
            all_fk_failures = db.execute("PRAGMA foreign_key_check").fetchall()
            if all_fk_failures:
                raise ValueError(f"Physical FK failures: {all_fk_failures}")
        except sqlite3.OperationalError as error:
            # Report known upstream mismatch; do not rewrite upstream or source DB.
            ignored_schema_issue = str(error)
            if '"group_messages" referencing "user"' not in ignored_schema_issue:
                raise
        counts = {table: db.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0]
                  for table in ("user", "post", "like", "follow", "comment")}
        trace_counts = dict(Counter(row[0] for row in db.execute("SELECT action FROM trace")))
        post_ids = [row[0] for row in db.execute("SELECT post_id FROM post ORDER BY post_id")]
    if counts != {"user": 3, "post": 3, "like": 3, "follow": 1, "comment": 1}:
        raise ValueError(f"Unexpected simulator counts: {counts}")
    media = {str(post_id): {"url": f"/seed-assets/oasis-{post_id}.jpg", "is_nsfw": index == 1}
             for index, post_id in enumerate(post_ids)}
    media_path = root / "media.json"
    media_path.write_text(json.dumps(media, indent=2), encoding="utf-8")
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "oasis_adapter"))
    from adapter import export
    before = hashlib.sha256(database.read_bytes()).hexdigest()
    # Each engine run has different timestamps; never reuse a snapshot namespace
    # for changed data, even though test databases are isolated.
    run_id = "oasis-engine-manual-" + root.name
    manifest = export(database, media_path, run_id, root / "export")
    if hashlib.sha256(database.read_bytes()).hexdigest() != before:
        raise ValueError("Adapter changed source SQLite")
    for filename, checksum in manifest["files"].items():
        if hashlib.sha256((root / "export" / filename).read_bytes()).hexdigest() != checksum:
            raise ValueError(f"Export checksum mismatch: {filename}")
    provenance = {"source": "upstream OASIS engine", "mode": "ManualAction", "llm_inference": False,
        "oasis_version": oasis.__version__, "oasis_commit": commit, "run_id": run_id, "counts": counts,
        "runtime_source": source_identity, "locked_dependencies": locked_versions,
        "trace_action_counts": trace_counts, "source_sha256": before,
        "physical_fk_checks": supported_fk_checks, "semantic_fk_checks": semantic_fk_checks,
        "ignored_upstream_schema_issue": ignored_schema_issue,
        "clock": "UTC-naive simulation start, real elapsed time, k=1",
        "media_labels": "explicit integration-test metadata, not moderation predictions"}
    (root / "provenance.json").write_text(json.dumps(provenance, indent=2), encoding="utf-8")
    print(json.dumps({"source": provenance["source"], "mode": provenance["mode"],
        "oasis_commit": commit, "verified_runtime_files": source_identity["verified_files"],
        "locked_dependencies": len(locked_versions), "counts": counts,
        "provenance_file": str(root / "provenance.json")}, ensure_ascii=True))


if __name__ == "__main__":
    run_root = Path(sys.argv[1]).resolve()
    upstream_root = Path(sys.argv[2]).resolve()
    run_root.mkdir(parents=True, exist_ok=False)
    asyncio.run(asyncio.wait_for(simulate(run_root, upstream_root), timeout=120))
